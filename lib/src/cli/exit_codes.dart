/// CLI の終了コード。
///
/// BSD の `sysexits.h` の慣例に従います。呼び出し側の多くは「0 かどうか」しか
/// 見ませんが、区分が揃っていないと文書が実態を説明できなくなるため、
/// 意味のある値を選んでいます。
///
/// `exitUsage` と `exitDataError` の境界は「入力ファイルを見なくても誤りと
/// 分かるか」で引いています。コマンドラインだけで判断できる誤りが
/// `exitUsage`、入力の内容と突き合わせて初めて分かる不一致が
/// `exitDataError` です。
library;

/// 正常終了。
const int exitSuccess = 0;

/// `EX_USAGE` — コマンドラインの誤り。
///
/// 未知のオプション、必須オプションの欠落、コマンド未指定、オプションの値が
/// それ自体として不正な場合。入力ファイルの内容には依存しません。
const int exitUsage = 64;

/// `EX_DATAERR` — 入力データの誤り。
///
/// 入力が仕様を満たさない場合と、利用者が指定した名前（シート名、ロケール、
/// 説明ヘッダ）が入力に存在しない場合。どちらも入力と突き合わせて初めて
/// 判明します。
const int exitDataError = 65;

/// `EX_NOINPUT` — 入力ファイルを読めない。
///
/// ファイルが存在しない、権限が無いなど。
const int exitNoInput = 66;

/// `EX_SOFTWARE` — 内部エラー。
///
/// 上記のいずれにも分類できない想定外の失敗。不具合として報告されるべき状態
/// であり、原因を追えるようスタックトレースも出力します。
const int exitSoftware = 70;

/// `EX_CANTCREAT` — 出力を作成できない。
///
/// 出力ディレクトリを作れない、ARB ファイルを書き込めないなど。
const int exitCantCreate = 73;
